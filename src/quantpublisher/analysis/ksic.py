def industry_division_code(induty_code: str | None) -> str | None:
    """업종코드의 앞 두 자리(중분류 코드)를 돌려준다. 숫자 두 자리 이상이 아니면 None."""
    if induty_code is None:
        return None
    code = induty_code.strip()
    return code[:2] if len(code) >= 2 and code.isdigit() else None


def industry_name(induty_code: str | None) -> str | None:
    """업종코드의 중분류 이름을 돌려준다. 알 수 없는 코드는 None (이름을 지어내지 않는다)."""
